#!/usr/bin/env python3
"""Regenerate src/pkg/workflow/PasClaw.Workflow.Export.Runtime.inc from
src/pkg/workflow/workflow_export_runtime.py -- the engine runtime that a
Python workflow export (`pasclaw workflow export <id> --lang python`) carries.

Edit the .py, then run:  python3 scripts/gen-workflow-export-inc.py
`--check` exits 1 when the .inc is out of date (make test-workflow-export runs it).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src/pkg/workflow/workflow_export_runtime.py")
DST = os.path.join(ROOT, "src/pkg/workflow/PasClaw.Workflow.Export.Runtime.inc")


def render():
    out = ["{ GENERATED by scripts/gen-workflow-export-inc.py from",
           "  src/pkg/workflow/workflow_export_runtime.py -- edit that file, not this one.",
           "  Included by PasClaw.Workflow.Export: the body of AddPythonRuntime(L). }"]
    with open(SRC, encoding="utf-8") as f:
        for line in f.read().splitlines():
            if any(ord(c) > 126 or (ord(c) < 32) for c in line):
                sys.exit("non-ASCII or control character in runtime line: %r" % line)
            if len(line) > 250:
                sys.exit("runtime line longer than 250 characters (a Delphi literal limit): %r" % line)
            out.append("L.Add('" + line.replace("'", "''") + "');")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        cur = open(DST, encoding="utf-8").read() if os.path.exists(DST) else ""
        if cur != text:
            print("FAIL: %s is out of date; run scripts/gen-workflow-export-inc.py" % DST)
            return 1
        return 0
    with open(DST, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
